import { create } from 'zustand';

/** The four tabs of the OMP settings page, in display order. */
export type OmpSettingsTab = 'common' | 'editing' | 'execution' | 'advanced';

/**
 * One row of a group: an engine setting id, or the read-summary preset row that
 * owns `read.summarize.enabled` plus the four thresholds it writes.
 */
export type OmpLayoutEntry = string | { readonly preset: 'readSummary' };

/**
 * Whether an entry is the preset row.
 *
 * The union is `string | { preset }`, so the test is "does this value carry the
 * tag"; a plain id can never be an object. `hasOwnProperty` checks the tag
 * without narrowing by `typeof`, which keeps the entry's declared contract as
 * the only description of its shape.
 */
export const isPresetEntry = (entry: OmpLayoutEntry): entry is { readonly preset: 'readSummary' } => (
  Object.prototype.hasOwnProperty.call(entry, 'preset')
);

/**
 * Every group id. Each one names the i18n key `settings.omp.group.<id>`, so the
 * union is what keeps a group title from being addressed by a raw string.
 */
export type OmpLayoutGroupId =
  | 'sessionBehavior'
  | 'shellAndTools'
  | 'toolsAndModels'
  | 'editing'
  | 'reading'
  | 'languageServer'
  | 'bashDetails'
  | 'evalRuntimes'
  | 'backgroundAndExecution'
  | 'toolDiscovery'
  | 'mcp'
  | 'output'
  | 'contextExperimental'
  | 'rules'
  | 'editReadThresholds'
  | 'guardsAndSubagents'
  | 'outputLimits'
  | 'extensions';

export interface OmpLayoutGroup {
  readonly id: OmpLayoutGroupId;
  readonly entries: readonly OmpLayoutEntry[];
}

export interface OmpLayoutTab {
  readonly id: OmpSettingsTab;
  readonly groups: readonly OmpLayoutGroup[];
}

