/** The setting id an entry draws; the preset row owns the read-summary switch. */
const ompLayoutEntryId = (entry: OmpLayoutEntry): string => (
  isPresetEntry(entry) ? 'read.summarize.enabled' : entry
);

/** Every setting id the page draws, in layout order. */
export const ompLayoutSettingIds = (): string[] => OMP_SETTINGS_LAYOUT.flatMap(
  (tab) => tab.groups.flatMap((group) => group.entries.map(ompLayoutEntryId)),
);

/** The tab that draws each entry's anchor. */
const TAB_BY_ENTRY: ReadonlyMap<string, OmpSettingsTab> = new Map(
  OMP_SETTINGS_LAYOUT.flatMap(
    (tab) => tab.groups.flatMap(
      (group) => group.entries.map((entry) => [ompLayoutEntryId(entry), tab.id] as const),
    ),
  ),
);

/**
 * The tab the Settings OMP page shows. It lives outside the page so a search
 * result can open the tab that holds its target before the page highlights it,
 * and so leaving the page and coming back keeps the tab.
 */
export const useOmpSettingsTabStore = create<{
  tab: OmpSettingsTab;
  setTab: (tab: OmpSettingsTab) => void;
}>((set) => ({
  tab: 'common',
  setTab: (tab) => set({ tab }),
}));

/**
 * The tab a Settings search anchor lands in: `omp.<settingId>` for a row,
 * `omp.preset.readSummary` for the read-summary preset, and `omp.configFile`
 * for the closing section that opens config.yml.
 */
export const ompSettingsTabForSearchTarget = (anchor: string): OmpSettingsTab | null => {
  if (!anchor.startsWith('omp.')) return null;
  const key = anchor.slice('omp.'.length);
  if (key === 'preset.readSummary' || key === 'read.summarize.enabled') return 'editing';
  if (key === 'configFile') return 'advanced';
  const tab = TAB_BY_ENTRY.get(key);
  return tab ?? null;
};
